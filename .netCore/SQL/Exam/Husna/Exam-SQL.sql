--Write a SQL query to find the total revenue generated by each product.
SELECT Product.ProductID,
Product.ProductName,
SUM(Product.Price*Sales.Quantity) AS TotalRevenue
FROM Product
JOIN Sales ON Product.ProductID=Sales.ProductID
GROUP BY Product.ProductID,Product.ProductName

--Write a SQL query to find the best-selling product based on quantity sold.

SELECT Product.ProductID,
Product.ProductName,
SUM(Sales.Quantity) AS TotalQuantitySold
FROM Product
JOIN Sales ON Product.ProductID=Sales.ProductID
GROUP BY Product.ProductID,Product.ProductName
ORDER BY 
TotalQuantitySold DESC;

--Write a SQL query to find the product(s) that have never been sold.
SELECT Product.ProductID,
Product.ProductName
FROM
Product
LEFT JOIN Sales ON Product.ProductID=Sales.ProductID
WHERE Sales.ProductID IS NULL;

