CREATE DATABASE Product_Details;
CREATE TABLE Product(
ProductID INT PRIMARY KEY,
ProductName VARCHAR(20),
Price DECIMAL(10,2)
);

CREATE TABLE Sales(
SaleID INT PRIMARY KEY,
ProductID INT, 
Quantity INT,
SaleDate DATE,
FOREIGN KEY (ProductID) REFERENCES Product(ProductID)
);

